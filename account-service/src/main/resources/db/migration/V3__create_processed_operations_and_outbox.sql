-- One row per command already applied. The primary key is what guarantees a command is never applied twice.
CREATE TABLE processed_operations (
    operation_id UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Messages written in the same transaction as the balance change, published to RabbitMQ afterwards.
CREATE TABLE outbox_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key VARCHAR(100)             NOT NULL,
    payload     TEXT                     NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at     TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_outbox_messages_unsent ON outbox_messages (id) WHERE sent_at IS NULL;
