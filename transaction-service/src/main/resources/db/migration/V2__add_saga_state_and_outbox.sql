-- Transactions created before the saga existed were processed synchronously, so they are all COMPLETED.
ALTER TABLE transactions
    ADD COLUMN status               VARCHAR(20)  NOT NULL DEFAULT 'COMPLETED',
    ADD COLUMN step                 VARCHAR(20),
    ADD COLUMN current_operation_id UUID,
    ADD COLUMN failure_reason       VARCHAR(500);

ALTER TABLE transactions ALTER COLUMN status DROP DEFAULT;

ALTER TABLE transactions
    ADD CONSTRAINT ck_transactions_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    ADD CONSTRAINT ck_transactions_step CHECK (step IN ('DEBIT_SOURCE', 'CREDIT_TARGET', 'REFUND_SOURCE')),
    ADD CONSTRAINT uk_transactions_current_operation_id UNIQUE (current_operation_id);

-- Messages written in the same transaction as the saga state change, published to RabbitMQ afterwards.
CREATE TABLE outbox_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key VARCHAR(100)             NOT NULL,
    payload     TEXT                     NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at     TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_outbox_messages_unsent ON outbox_messages (id) WHERE sent_at IS NULL;
